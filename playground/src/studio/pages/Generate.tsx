import { useEffect, useRef, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { toast } from 'react-toastify';
import { Download, Eye, FileJson, Upload } from 'lucide-react';
import { useProjects } from '../lib/useProjects';
import { useSelectedProject } from '../lib/useSelectedProject';
import { useSettings } from '../lib/settings';
import ProjectSelect from '../components/ProjectSelect';
import FieldEditor from '../components/FieldEditor';
import { PdfPreviewModal, errMsg } from '../components/ui';
import { getTemplateFields, initialValues, validateValues } from '../lib/fields';
import { applyFilenamePattern, deliverPdf, downloadJson, generatePdf } from '../lib/pdfIO';
import { getMeta, importFromJson, patchMeta } from '../lib/storage';

export default function Generate() {
  const nav = useNavigate();
  const { settings } = useSettings();
  const { projects, loading, refresh } = useProjects();
  const { selected, select } = useSelectedProject(projects);
  const [values, setValues] = useState<Record<string, string>>({});
  const [errors, setErrors] = useState<Record<string, string>>({});
  const [preview, setPreview] = useState<Uint8Array | null>(null);
  const [busy, setBusy] = useState(false);
  const fileRef = useRef<HTMLInputElement>(null);

  useEffect(() => {
    if (selected) setValues(initialValues(selected.template, selected.inputs[0]));
    setErrors({});
  }, [selected?.id]); // eslint-disable-line react-hooks/exhaustive-deps

  const fields = selected ? getTemplateFields(selected.template) : [];
  const config = selected ? getMeta(selected).formFields : {};

  const build = async () => {
    if (!selected) throw new Error('Select a project first.');
    const errs = validateValues(fields, values, config);
    setErrors(errs);
    if (Object.keys(errs).length) throw new Error('Please fix the highlighted fields.');
    return generatePdf({ template: selected.template, inputs: [values], settings, title: selected.title });
  };
  const run = async (fn: (data: Uint8Array) => void) => {
    setBusy(true);
    try { fn(await build()); } catch (e) { toast.error(errMsg(e)); } finally { setBusy(false); }
  };

  const importFile = async (f: File) => {
    try {
      const created = await importFromJson(await f.text(), f.name.replace(/\.json$/i, ''));
      toast.success(`Imported “${created[0].title}”`);
      await refresh();
      select(created[0].id);
    } catch (e) { toast.error(`Import failed: ${errMsg(e)}`); }
  };

  return (
    <div className="nx-page">
      <h1 className="nx-h1">Generate PDF</h1>
      <p className="nx-sub">Fill in your template’s fields, preview the result and download a real PDF generated by PDFme.</p>
      <div className="nx-row" style={{ marginTop: 16, alignItems: 'flex-end' }}>
        <ProjectSelect projects={projects} value={selected?.id ?? ''} onChange={select} loading={loading} />
        <button className="nx-btn" onClick={() => fileRef.current?.click()}><Upload size={16} /> Import template JSON</button>
        <input ref={fileRef} type="file" accept=".json,application/json" hidden onChange={(e) => { const f = e.target.files?.[0]; e.target.value = ''; if (f) void importFile(f); }} />
      </div>
      {selected && (
        <div className="nx-card" style={{ marginTop: 18 }}>
          <FieldEditor fields={fields} values={values} config={config} errors={errors}
            onChange={(n, v) => setValues((s) => ({ ...s, [n]: v }))} />
          <div className="nx-row" style={{ marginTop: 18 }}>
            <button className="nx-btn" disabled={busy} onClick={() => void run(setPreview)}><Eye size={16} /> Preview</button>
            <button className="nx-btn primary" disabled={busy} onClick={() => void run((d) => deliverPdf(d, applyFilenamePattern(settings.filenamePattern, selected.title), settings.exportMode))}>
              <Download size={16} /> Download PDF
            </button>
            <button className="nx-btn" onClick={() => downloadJson(selected.template, `${selected.title}.pdfme-template`)}><FileJson size={16} /> Export template JSON</button>
            <button className="nx-btn" onClick={() => void patchMeta({ ...selected, inputs: [values] }, {}).then(() => toast.success('Field values saved to project')).catch((e) => toast.error(errMsg(e)))}>Save values</button>
            <button className="nx-btn" onClick={() => nav(`/studio/editor/${encodeURIComponent(selected.id)}`)}>Edit design</button>
          </div>
        </div>
      )}
      {preview && selected && <PdfPreviewModal data={preview} filename={selected.title} onClose={() => setPreview(null)} />}
    </div>
  );
}
